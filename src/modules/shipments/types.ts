export type Amount = number | null;
export type Stage = "proposed" | "ordered" | "actuals" | "closed";
export type ShipmentWine = {
    id: string;
    productId: string | null;
    name: string;
    producer: string;
    vintage: string;
    sku: string;
    country: string;
    variety: string;
    imageUrl: string | null;
    pallet: string;
    qty: number;
    caseSize: Amount;
    casePrice: Amount;
    discount: Amount;
    abv: Amount;
    ml: Amount;
    registeredPrice: Amount;
    salesPrice: Amount;
    duty: Amount;
    excise: Amount;
    local: Amount;
    funds: Amount;
    assessedQty: Amount;
};
export type Expense = {
    id: string;
    name: string;
    category: string;
    pallet: string;
    status: "estimate" | "actual";
    amount: Amount;
    vat: Amount;
    currency: string;
    fx: Amount;
    note: string;
};
export type ShipmentData = {
    id: string;
    name: string;
    supplier: string;
    reference: string;
    currency: string;
    fx: Amount;
    incoterm: string;
    stage: Stage;
    arrivalDate: string;
    orderDate: string;
    expectedDate: string;
    taxMode: "model" | "assessed";
    importVatMode: "sku-7" | "recorded";
    importVat: Amount;
    rules: {
        valueRate: Amount;
        alcoholRate: Amount;
        localRate: Amount;
    };
    pallets: string[];
    wines: ShipmentWine[];
    expenses: Expense[];
    forecastId: string | null;
    actualConfirmed: boolean;
};
export type Snapshot = {
    id: string;
    name: string;
    kind: "Forecast" | "Actual (partial)" | "Actual (complete)";
    created: string;
    note: string;
    data: ShipmentData;
    calculation?: Calculation;
};
export type ShipmentNote = {
    id: string;
    text: string;
    author: string;
    created: string;
};
export type Shipment = ShipmentData & {
    version: number;
    updatedAt: string | null;
    snapshots: Snapshot[];
    notes: ShipmentNote[];
};
export type CostLine = {
    id: string;
    qty: number;
    netForeign: number;
    goods: number;
    excise: number;
    local: number;
    funds: number;
    duty: number;
    tax: number;
    shared: number;
    cost: number;
    unit: number;
    vatBase: number;
    importVat: number;
};
export type Calculation = {
    errors: string[];
    lines: CostLine[];
    allocations: {
        name: string;
        amount: number;
        values: number[];
    }[];
    quantity: number;
    goods: number | null;
    tax: number | null;
    expenses: number | null;
    importVat: number | null;
    serviceVat: number | null;
    vat: number | null;
    total: number | null;
    cash: number | null;
    source: number | null;
    estimated: number;
};
